def _fixture(fixture_id: str = "fixture-1") -> dict:
    return {
        "id": fixture_id,
        "category": "generic-prop",
        "profile": "generic-prop",
        "source": {
            "type": "repo-generated",
            "license": "MIT",
            "provenance": "generated by this test",
        },
        "projectPath": "../tracked-fixture/project.json",
        "expectedRoute": "reference→validate→cast→render→metrics→review",
        "requiredPasses": ["beauty"],
        "views": [{"id": "front", "role": "primary"}],
        "heldOutViews": [],
    }


def _manifest(*fixtures: dict) -> dict:
    return {
        "schemaVersion": 1,
        "name": "test-benchmark",
        "fixtures": list(fixtures),
    }


def _write_manifest(root: Path, *fixtures: dict) -> tuple[Path, Path]:
    tracked = root / "tracked-fixture"
    tracked.mkdir(parents=True)
    (tracked / "project.json").write_text("{}\n", encoding="utf-8")
    manifests = root / "manifests"
    manifests.mkdir()
    path = manifests / "benchmark.json"
    path.write_text(json.dumps(_manifest(*fixtures)), encoding="utf-8")
    return path, tracked


def _successful_run(out_dir: str, *, reason: str = "accept", ok: bool = True) -> dict:
    output = Path(out_dir)
    pass_path = output / "renders" / "front" / "beauty.png"
    pass_path.parent.mkdir(parents=True, exist_ok=True)
    pass_path.write_bytes(b"test-render")
    render_set_path = output / "render-set.json"
    render_set_path.write_text(
        json.dumps(
            {
                "schemaVersion": 1,
                "views": [
                    {
                        "id": "front",
                        "passes": {
                            "beauty": {
                                "path": str(pass_path),
                                "hash": "sha256:test",
                            }
                        },
                    }
                ],
            }
        ),
        encoding="utf-8",
    )
    return {
        "ok": ok,
        "reason": reason,
        "stages": ["validate", "cast", "render", "metrics", "review"],
        "artifacts": {"renderSet": str(render_set_path)},
    }


class BenchmarkManifestTests(unittest.TestCase):
    def test_complete_fixture_is_accepted_and_schema_exposes_contract(self) -> None:
        value = _manifest(_fixture())
        self.assertEqual(validate_manifest(value), [])
        parsed = parse_manifest(value)
        self.assertEqual(parsed, value)
        self.assertIsNot(parsed, value)

        required = manifest_schema()["properties"]["fixtures"]["items"]["required"]
        for field in (
            "id",
            "category",
            "profile",
            "source",
            "views",
            "heldOutViews",
            "requiredPasses",
            "expectedRoute",
        ):
            self.assertIn(field, required)

    def test_missing_source_or_provenance_is_rejected(self) -> None:
        missing_source = _fixture()
        del missing_source["source"]
        errors = validate_manifest(_manifest(missing_source))
        self.assertTrue(any(".source: missing required field" in error for error in errors), errors)

        missing_provenance = _fixture()
        del missing_provenance["source"]["provenance"]
        errors = validate_manifest(_manifest(missing_provenance))
        self.assertTrue(any(".source.provenance: missing required field" in error for error in errors), errors)

    def test_duplicate_fixture_ids_are_rejected(self) -> None:
        first = _fixture("duplicate")
        second = copy.deepcopy(first)
        errors = validate_manifest(_manifest(first, second))
        self.assertTrue(any("duplicate fixture id 'duplicate'" in error for error in errors), errors)
        with self.assertRaisesRegex(ValueError, "duplicate fixture id"):
            parse_manifest(_manifest(first, second))


class BenchmarkRunnerTests(unittest.TestCase):
    def test_missing_render_output_is_an_explicit_failure(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            manifest_path, _tracked = _write_manifest(root, _fixture())
            out = root / "work" / "benchmark"
            production_result = {
                "ok": True,
                "reason": "accept",
                "stages": ["validate", "cast", "render", "review"],
                "artifacts": {},
            }
            with patch("engine.orchestration.run.run_production", return_value=production_result):
                report = run_benchmark(manifest_path, out_dir=out)

            self.assertTrue(report["ok"])
            self.assertEqual(report["results"][0]["status"], "missing-render")
            self.assertIn("did not report a renderSet", report["results"][0]["reason"])
            self.assertEqual(report["summary"]["total"], 1)
            self.assertEqual(report["summary"]["byStatus"]["missing-render"], 1)
            self.assertEqual(report["summary"]["passRate"], 0.0)

    def test_aggregate_denominator_includes_all_failed_runs(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            fixtures = [_fixture("passing"), _fixture("failing"), _fixture("missing")]
            manifest_path, _tracked = _write_manifest(root, *fixtures)
            out = root / "work" / "benchmark"

            def fake_run(_project_path: str, *, out_dir: str) -> dict:
                fixture_id = Path(out_dir).name
                if fixture_id == "passing":
                    return _successful_run(out_dir)
                if fixture_id == "failing":
                    return {
                        "ok": False,
                        "reason": "character gate failed",
                        "stages": ["validate"],
                        "artifacts": {},
                    }
                return {
                    "ok": True,
                    "reason": "accept",
                    "stages": ["render", "review"],
                    "artifacts": {},
                }

            with patch("engine.orchestration.run.run_production", side_effect=fake_run):
                report = run_benchmark(manifest_path, out_dir=out)

            summary = report["summary"]
            self.assertEqual(summary["total"], 3)
            self.assertEqual(summary["byStatus"]["pass"], 1)
            self.assertEqual(summary["byStatus"]["fail"], 1)
            self.assertEqual(summary["byStatus"]["missing-render"], 1)
            self.assertEqual(summary["passRate"], 0.3333)
            self.assertEqual(summary["failureRate"], 0.6667)

    def test_generated_artifacts_stay_outside_tracked_fixture_directory(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            manifest_path, tracked = _write_manifest(root, _fixture())
            out = root / "work" / "benchmark"
            observed_out_dirs: list[Path] = []

            def fake_run(_project_path: str, *, out_dir: str) -> dict:
                observed_out_dirs.append(Path(out_dir).resolve())
                return _successful_run(out_dir)

            with patch("engine.orchestration.run.run_production", side_effect=fake_run):
                report = run_benchmark(manifest_path, out_dir=out)

            self.assertEqual(report["results"][0]["status"], "pass")
            self.assertEqual(observed_out_dirs, [(out / "fixture-1").resolve()])
            self.assertEqual(
                sorted(path.name for path in tracked.iterdir()),
                ["project.json"],
            )
            self.assertTrue((out / "benchmark-report.json").is_file())

    def test_review_revision_is_recorded_as_conditional(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            manifest_path, _tracked = _write_manifest(root, _fixture())
            out = root / "work" / "benchmark"

            def fake_run(_project_path: str, *, out_dir: str) -> dict:
                return _successful_run(out_dir, reason="revise", ok=False)

            with patch("engine.orchestration.run.run_production", side_effect=fake_run):
                report = run_benchmark(manifest_path, out_dir=out)

            self.assertEqual(report["results"][0]["status"], "conditional")
            self.assertEqual(report["summary"]["byStatus"]["conditional"], 1)
            self.assertEqual(report["summary"]["failureRate"], 0.0)


